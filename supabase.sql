alter table public.followers enable row level security;
alter table public.groups enable row level security;
alter table public.group_members enable row level security;
alter table public.group_messages enable row level security;
alter table public.notifications enable row level security;

-- Helper: admin check. First admin must be set manually once in SQL Editor.
create or replace function public.is_admin(uid uuid default auth.uid())
returns boolean language sql stable security definer set search_path = public
as $$ select exists(select 1 from public.profiles where id = uid and role = 'Администратор'); $$;

-- Profile trigger
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles(id, username, about, avatar_url)
  values (
    new.id,
    left(coalesce(nullif(new.raw_user_meta_data->>'username',''), 'user_' || left(new.id::text,8)), 32),
    coalesce(new.raw_user_meta_data->>'about',''),
    coalesce(new.raw_user_meta_data->>'avatar_url','')
  ) on conflict (id) do nothing;
  return new;
end; $$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute function public.handle_new_user();

