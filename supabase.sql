create or replace function public.protect_profile_role()
returns trigger language plpgsql security definer set search_path = public
as $$
begin
  if not public.is_admin(auth.uid()) and new.role <> old.role then
    new.role := old.role;
  end if;
  return new;
end; $$;

drop trigger if exists protect_profile_role on public.profiles;
create trigger protect_profile_role before update on public.profiles for each row execute function public.protect_profile_role();

-- RPCs for safe privileged actions
create or replace function public.admin_set_role(target_user uuid, new_role text)
returns void language plpgsql security definer set search_path = public
as $$ begin
  if not public.is_admin(auth.uid()) then raise exception 'Only administrators can change roles'; end if;
  if new_role not in ('Пользователь','VIP','Администратор','Мем Года','Модератор','Разработчик','Дизайнер','Геймер','Мемолог','Легенда','OG','Premium','Контентмейкер','Музыкант','Фотограф','Гений','Сигма','Топ','Активист','Верифицирован') then raise exception 'Invalid role'; end if;
  update public.profiles set role = new_role where id = target_user;
end; $$;

grant execute on function public.admin_set_role(uuid,text) to authenticated;

